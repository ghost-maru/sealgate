import { JsonRpcProvider, KeyPairSigner, Account, parseNearAmount } from 'near-api-js';
import { readFileSync } from 'node:fs';
console.log('parseNearAmount(2) =', JSON.stringify(parseNearAmount('2')), typeof parseNearAmount('2'));
const provider = new JsonRpcProvider({ url: 'https://rpc.testnet.near.org' });
const APP = 'app.sealgate-ghost.testnet'; const BUYER = 'sgbuyer-ghost.testnet';
const { secretKey } = JSON.parse(readFileSync('.keys/buyer.json', 'utf8'));
const buyer = new Account(BUYER, provider, await KeyPairSigner.fromSecretKey(secretKey));
const r = await buyer.callFunction({ contractId: APP, methodName: 'deposit', args: {}, gas: '100000000000000', attachedDeposit: BigInt(parseNearAmount('1')) });
console.log('deposit result keys:', r && typeof r === 'object' ? Object.keys(r) : typeof r, JSON.stringify(r).slice(0,200));
const v = await provider.query({ request_type: 'call_function', finality: 'final', account_id: APP, method_name: 'get_balance', args_base64: Buffer.from(JSON.stringify({ account: BUYER })).toString('base64') });
console.log('get_balance after:', Buffer.from(v.result).toString('utf8'));
